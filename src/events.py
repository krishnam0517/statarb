class Event:
    """
    Base class for all event types in the trading architecture.
    """
    pass


class MarketEvent(Event):
    """
    Handles the arrival of new market data (e.g., daily price bar).
    Triggered by the DataHandler to notify the Strategy.
    """
    def __init__(self):
        self.type = 'MARKET'


class SignalEvent(Event):
    """
    Generated by the Strategy when a trading rule triggers 
    (e.g., cointegration spread divergence threshold breached).
    """
    def __init__(self, timestamp, ticker: str, signal_type: str, strength: float = 1.0):
        self.type = 'SIGNAL'
        self.timestamp = timestamp
        self.ticker = ticker
        self.signal_type = signal_type.upper()
        self.strength = strength


class OrderEvent(Event):
    """
    Generated by the Portfolio/Position Sizer when a SignalEvent 
    is translated into a specific order instruction for the ExecutionHandler.
    """
    def __init__(self, timestamp, ticker: str, order_type: str, quantity: int, direction: str):
        self.type = 'ORDER'
        self.timestamp = timestamp
        self.ticker = ticker
        self.order_type = order_type.upper()
        self.quantity = quantity
        self.direction = direction.upper()

    def __repr__(self):
        return f"OrderEvent(Time={self.timestamp}, Ticker={self.ticker}, Type={self.order_type}, Qty={self.quantity}, Dir={self.direction})"


class FillEvent(Event):
    """
    Generated by the ExecutionHandler (simulated broker or live gateway) 
    when an order has been executed. Consumed by the Portfolio to update positions.
    """
    def __init__(self, timestamp, ticker: str, quantity: int, direction: str, fill_cost: float, commission: float = None):
        self.type = 'FILL'
        self.timestamp = timestamp
        self.ticker = ticker
        self.quantity = quantity
        self.direction = direction.upper()
        self.fill_cost = fill_cost
        if commission is None:
            self.commission = self.calculate_default_commission()
        else:
            self.commission = commission

    def calculate_default_commission(self) -> float:
        return max(1.00, self.quantity * 0.005)

    def __repr__(self):
        return f"FillEvent(Time={self.timestamp}, Ticker={self.ticker}, Qty={self.quantity}, Dir={self.direction}, Cost={self.fill_cost:.2f}, Comm={self.commission:.2f})"